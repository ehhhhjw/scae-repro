"""X9: **cross-model reproduction** of collision isolation and the judge mechanism. API, tiny budget.

Why this experiment
-------------------
The external-validity limitation the paper states itself: "the results come from a single agent
and a single model; attributing the displacement to the generality of full-trace judging requires
a cross-model reproduction". This experiment is exactly that patch.

Why not X3
----------
The new key's measured rate ceiling is **10 calls / 60 minutes** (the endpoint replies outright
with `your current API calls exceeded 10 per 60.0 minutes`). X3 needs 1680 continuations, and each
continuation makes the agent run another 15-20 steps ≈ 15-20 calls → about 3400 hours. **Three
orders of magnitude off, infeasible.**
A judge verdict, by contrast, **needs only 1 call each** (no tools, one-shot thread), hence

    25 episodes × 2 conditions (full / prefix) = 50 calls ≈ 5.5 hours

The same batch of verdicts also reproduces "is the judge picking gold provenance steps too" at
**zero extra cost**.

Estimands (isomorphic to the original experiment)
-------------------------------------------------
  C = pos(judge_full) − pos(judge_prefix)      collision-isolation contrast
  prefix truncation rule carried over: upto = max(2, round(n_steps × 0.6))
  judge enrichment = share of judge top-1 on gold provenance steps vs their share of all steps

⚠️ Caveats introduced by the model difference
---------------------------------------------
The original judge is gpt-5.5-0424-global; here it is the qwen family. That is **precisely** the
point of a cross-model reproduction. Note though: the scored traces are still generated by
gpt-5.5, so what is swapped is the **scorer**, not the **scoree** -- exactly the thing that
limitation in the paper talks about.

Criteria (pre-registered)
-------------------------
| Result | Conclusion |
|---|---|
| C significantly > 0 and comparable in magnitude | collider bias is **not a quirk of one judge**, the paper's external-validity limitation is lifted |
| C significantly > 0 but much smaller | the mechanism exists but its strength is model-dependent, report both numbers as they are |
| C ≈ 0 or reversed | the original result **does not generalize across models**, and must be narrowed to "a statement about that judge" |
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
import time
import traceback
from collections import deque
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from pilot.analyze.judge_http import judge_http              # noqa: E402
from pilot.harness import rollout as R                        # noqa: E402
from pilot.probes import task as T                            # noqa: E402
from pilot.analyze.v3k_trace_causal import gold_relation, boot_ci, paired_ci  # noqa: E402


class RateLimiter:
    """Sliding-window rate limit. The measured endpoint ceiling is 10 calls / 60 minutes.

    Blocks before each call until the window has room; when the endpoint reports a rate-limit
    overrun, `penalize()` can add extra backoff.
    """

    def __init__(self, max_calls: int, window_s: float, safety_s: float = 20.0,
                 assume_full: bool = False):
        self.max_calls = max_calls
        self.window_s = window_s
        self.safety_s = safety_s
        self.stamps: deque[float] = deque()
        if assume_full:
            # the window may already be full from earlier probing at startup; conservatively
            # count from "just used up", so the first call waits a whole window instead of
            # hitting the limit right away.
            now = time.time()
            for _ in range(max_calls):
                self.stamps.append(now)

    def acquire(self) -> None:
        while True:
            now = time.time()
            while self.stamps and now - self.stamps[0] > self.window_s:
                self.stamps.popleft()
            if len(self.stamps) < self.max_calls:
                self.stamps.append(now)
                return
            wait = self.window_s - (now - self.stamps[0]) + self.safety_s
            print(f"    [rate] window full {len(self.stamps)}/{self.max_calls}, "
                  f"waiting {wait/60:.1f} min", flush=True)
            time.sleep(max(5.0, wait))

    def penalize(self, extra_s: float) -> None:
        print(f"    [rate] endpoint reported an overrun, adding {extra_s/60:.1f} min of backoff", flush=True)
        time.sleep(extra_s)


def rate_limited_error(res: dict | None) -> bool:
    raw = json.dumps(res or {}, ensure_ascii=False)
    # the escaped literal is the "exceeded" wording of the endpoint's Chinese rate-limit reply
    return ("\u8d85\u8fc7\u4e86" in raw) or ("IRC-001" in raw) or ("rate" in raw.lower()
                                                                   and "limit" in raw.lower())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--attr-dir", default="pilot/runs/full_attr")
    ap.add_argument("--runs-root", default="pilot/runs/full_locate")
    ap.add_argument("--out", default="pilot/runs/x9_judge_crossmodel.jsonl")
    ap.add_argument("--report", default="pilot/runs/x9_judge_crossmodel.json")
    ap.add_argument("--model", default="qwen3.6-plus")
    ap.add_argument("--model-provider", default="idealab")
    ap.add_argument("--wire-api", default="responses",
                    help="codex 0.145 dropped chat support (`wire_api = \"chat\"` is no "
                         "longer supported), so only responses is usable")
    ap.add_argument("--workdir", default="pilot/runs/x9_work")
    ap.add_argument("--codex-bin", default="codex")
    ap.add_argument("--limit", type=int, default=25,
                    help="number of episodes; each costs 2 calls")
    ap.add_argument("--prefix-frac", type=float, default=0.6)
    ap.add_argument("--max-calls", type=int, default=10)
    ap.add_argument("--window-min", type=float, default=60.0)
    ap.add_argument("--turn-timeout", type=float, default=300.0)
    ap.add_argument("--max-retries", type=int, default=4,
                    help="retries when the endpoint rate-limits (a rate limit is not a failure)")
    ap.add_argument("--backoff-min", type=float, default=20.0,
                    help="backoff in minutes after a rate limit")
    ap.add_argument("--assume-window-full", action="store_true",
                    help="assume the rate window is full at startup (wait one window before the first call)")
    ap.add_argument("--analyze-only", action="store_true")
    args = ap.parse_args()

    insts = {i.instance_id: i for i in T.load_instances()}
    roll = {p.stem.split("__k")[0]: p
            for p in Path(args.runs_root).glob("shard*/rollouts/*.jsonl")}
    recs = []
    for f in sorted(Path(args.attr_dir).glob("shard*/attribution.jsonl")):
        recs += [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    # keep only episodes whose two judge conditions both parsed in the original run, so pairs match
    usable = [r for r in recs
              if r.get("judge_full_top1_pos") is not None
              and r.get("judge_prefix_top1_pos") is not None
              and r["instance_id"] in roll]
    usable.sort(key=lambda r: r["instance_id"])
    print(f"pairable episodes in the original experiment: {len(usable)}, taking the first {args.limit}")

    out_path = Path(args.out)
    done: dict[str, dict] = {}
    if out_path.exists():
        for line in out_path.read_text().splitlines():
            if line.strip():
                d = json.loads(line)
                done[d["instance_id"]] = d
        print(f"resuming from checkpoint: {len(done)} already done")

    todo = [r for r in usable[:args.limit] if r["instance_id"] not in done]

    if todo and not args.analyze_only:
        import os
        if not os.environ.get("IDEALAB_API_KEY"):
            print("❌ IDEALAB_API_KEY is not set, judge calls are bound to fail, aborting.")
            return 2
        Path(args.workdir).mkdir(parents=True, exist_ok=True)
        rl = RateLimiter(args.max_calls, args.window_min * 60,
                         assume_full=args.assume_window_full)
        n_fail = 0
        with open(out_path, "a", encoding="utf-8") as fh:
            for i, r in enumerate(todo, 1):
                iid = r["instance_id"]
                inst = insts[iid]
                base = R.load(roll[iid])
                st = R.steps(base)
                upto = max(2, int(round(len(st) * args.prefix_frac)))
                rec = {"instance_id": iid, "model": args.model,
                       "n_steps": len(st), "prefix_upto": upto}
                for mode in ("full", "prefix"):
                    print(f"  [{i}/{len(todo)}] {iid} judge={mode}", flush=True)
                    res = None
                    for attempt in range(1, args.max_retries + 1):
                        rl.acquire()
                        try:
                            res = judge_http(
                                base, inst, r.get("Y", 0), args.model,
                                mode=mode,
                                prefix_upto=(upto if mode == "prefix" else None),
                                timeout=args.turn_timeout)
                        except Exception as exc:  # noqa: BLE001
                            res = {"parsed": False,
                                   "error": f"{type(exc).__name__}: {str(exc)[:200]}"}
                        # a rate limit is not a failure: back off and retry, not a parse failure
                        if rate_limited_error(res) and attempt < args.max_retries:
                            rl.penalize(args.backoff_min * 60)
                            continue
                        break
                    rec[mode] = res
                    if not (res or {}).get("parsed"):
                        n_fail += 1
                fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
                fh.flush()          # flush per record, a crash must not lose spent quota
                done[iid] = rec
                # stop right away if both conditions fail on the first episode
                rate_only = all(rate_limited_error(rec.get(m))
                                for m in ("full", "prefix"))
                if (i == 1 and not rate_only
                        and not any((rec.get(m) or {}).get("parsed")
                                    for m in ("full", "prefix"))):
                    print("❌ FAIL-FAST: neither condition parsed on the first episode, aborting.")
                    for m in ("full", "prefix"):
                        print(f"     {m}: {json.dumps(rec.get(m), ensure_ascii=False)[:220]}")
                    return 3
        print(f"\ndone, {n_fail} calls failed to parse")

    # ------------------------------------------------------------- analysis
    orig = {r["instance_id"]: r for r in usable}
    pairs = []
    for iid, d in done.items():
        f_, p_ = d.get("full") or {}, d.get("prefix") or {}
        if not (f_.get("parsed") and p_.get("parsed")):
            continue
        o = orig.get(iid)
        if o is None:
            continue
        pairs.append({
            "instance_id": iid,
            "new_full_pos": f_["top1_pos"], "new_prefix_pos": p_["top1_pos"],
            "new_full_step": f_["top1_step"], "new_prefix_step": p_["top1_step"],
            "old_full_pos": o["judge_full_top1_pos"],
            "old_prefix_pos": o["judge_prefix_top1_pos"],
            "old_full_step": o.get("judge_full_top1_step"),
        })
    if not pairs:
        print("\nno analyzable samples (no successful verdicts yet)")
        return 0

    nd = [x["new_full_pos"] - x["new_prefix_pos"] for x in pairs]
    od = [x["old_full_pos"] - x["old_prefix_pos"] for x in pairs]
    from math import comb
    nz = [d for d in nd if d != 0]
    k = sum(1 for d in nz if d > 0)
    sign_p = (min(1.0, 2 * sum(comb(len(nz), i) for i in range(k, len(nz) + 1))
                  / 2 ** len(nz)) if nz else None)

    # judge enrichment (same batch of verdicts, zero extra calls)
    enrich, base_share = [], []
    for x in pairs:
        inst = insts[x["instance_id"]]
        st = R.steps(R.load(roll[x["instance_id"]]))
        rel = gold_relation(st, set(inst.gold))
        allst = sorted(rel)
        s = x["new_full_step"]
        if s in rel:
            enrich.append(1.0 if rel[s]["any_gold"] else 0.0)
            base_share.append(sum(1 for t in allst if rel[t]["any_gold"]) / len(allst))

    rep = {
        "model": args.model, "n_paired": len(pairs),
        "COLLIDER_REPLICATION": {
            "new_model_displacement": boot_ci(nd),
            "orig_model_displacement_same_episodes": boot_ci(od),
            "new_minus_orig": paired_ci(nd, od),
            "n_later": sum(1 for d in nd if d > 0), "n_tied": len(nd) - len(nz),
            "sign_test_p": sign_p,
            "new_full_pos_mean": round(statistics.mean(
                x["new_full_pos"] for x in pairs), 4),
            "new_prefix_pos_mean": round(statistics.mean(
                x["new_prefix_pos"] for x in pairs), 4),
        },
        "JUDGE_ENRICHMENT": {
            "observed": boot_ci(enrich),
            "baseline_all_steps": boot_ci(base_share),
            "diff": paired_ci(enrich, base_share),
        },
        "pairs": pairs,
    }
    Path(args.report).write_text(json.dumps(rep, ensure_ascii=False, indent=2),
                                 encoding="utf-8")

    cr = rep["COLLIDER_REPLICATION"]
    print(f"\n=== cross-model reproduction of collision isolation ({args.model}, n={len(pairs)}) ===")
    print(f"  new model full−prefix displacement {cr['new_model_displacement']['mean']:+.4f} "
          f"CI{cr['new_model_displacement']['ci95']}")
    print(f"  original model (same episodes)     {cr['orig_model_displacement_same_episodes']['mean']:+.4f} "
          f"CI{cr['orig_model_displacement_same_episodes']['ci95']}")
    d = cr["new_minus_orig"]
    if "note" not in d:
        print(f"  difference between the models {d['diff']:+.4f} CI{d['ci95']}  "
              f"{'significant' if d['significant'] else 'not significant'}")
    print(f"  moved later {cr['n_later']}/{len(nd)} (ties {cr['n_tied']}), "
          f"sign test p={cr['sign_test_p']}")
    print(f"  mean position full {cr['new_full_pos_mean']} vs prefix {cr['new_prefix_pos_mean']}")
    je = rep["JUDGE_ENRICHMENT"]
    if "note" not in je["observed"]:
        print(f"\n=== judge enrichment (same batch of verdicts, zero extra calls) ===")
        print(f"  landing on gold provenance steps {je['observed']['mean']:.4f} "
              f"CI{je['observed']['ci95']}   baseline {je['baseline_all_steps']['mean']:.4f}")
        dd = je["diff"]
        if "note" not in dd:
            print(f"  difference {dd['diff']:+.4f} CI{dd['ci95']}  "
                  f"{'significant' if dd['significant'] else 'not significant'}")
    print(f"\n→ {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
